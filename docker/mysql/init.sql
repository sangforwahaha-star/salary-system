CREATE DATABASE IF NOT EXISTS salary_system CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE salary_system;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  employee_no VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  department VARCHAR(100) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('admin', 'dept_admin', 'employee') DEFAULT 'employee',
  status TINYINT DEFAULT 1 COMMENT '1=在职 0=停用',
  must_change_password TINYINT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_employee_no (employee_no),
  INDEX idx_department (department)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS salaries (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  period VARCHAR(7) NOT NULL COMMENT '发放月份 YYYY-MM',
  salary DECIMAL(12,2) DEFAULT 0.00 COMMENT '薪酬（=绩效+绩效调整）',
  pension_insurance_1 DECIMAL(12,2) DEFAULT 0.00 COMMENT '养老保险1',
  pension_insurance_2 DECIMAL(12,2) DEFAULT 0.00 COMMENT '养老保险2',
  medical_insurance DECIMAL(12,2) DEFAULT 0.00 COMMENT '医疗保险',
  unemployment_insurance DECIMAL(12,2) DEFAULT 0.00 COMMENT '失业保险',
  housing_fund_deduction DECIMAL(12,2) DEFAULT 0.00 COMMENT '代扣公积金',
  income_tax DECIMAL(12,2) DEFAULT 0.00 COMMENT '代扣税',
  target_linked_amount DECIMAL(12,2) DEFAULT 0.00 COMMENT '目标挂钩部分',
  net_performance_pay DECIMAL(12,2) DEFAULT 0.00 COMMENT '绩效实发数',
  total_deduction DECIMAL(12,2) DEFAULT 0.00 COMMENT '扣款合计',
  remark VARCHAR(500) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_user_period (user_id, period),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_period (period)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS operation_logs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT,
  operation_type VARCHAR(50) NOT NULL,
  operation_content TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS import_records (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT,
  import_type ENUM('employees', 'salaries') NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  success_count INT DEFAULT 0,
  fail_count INT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

